function replaceBlock(startMarker, endMarker, newContent) {
  const si = src.indexOf(startMarker);
  if (si === -1) throw new Error('Start marker not found: ' + startMarker.slice(0, 80));
  const ei = src.indexOf(endMarker, si);
  if (ei === -1) throw new Error('End marker not found: ' + endMarker.slice(0, 80));
  // src.slice(ei) JÁ inclui o endMarker — newContent NÃO deve terminá-lo
  src = src.slice(0, si) + newContent + src.slice(ei);
}

